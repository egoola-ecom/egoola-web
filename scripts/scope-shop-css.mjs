// Builds src/styles/shop.css from the legacy site's CSS (design/webapp-css/).
//
// The legacy CSS is global (it styles html, body, ul, table ...). The admin and
// seller panels must not be touched by it, so every selector is prefixed with
// `.eg-shop`, the wrapper class of the buyer layout. html / body / :root become
// the wrapper itself. Font and image URLs point at /shop/ (public/shop/), and the
// two named fonts use the next/font variables set in the buyer layout.
//
// Run: node scripts/scope-shop-css.mjs
import { readFileSync, writeFileSync } from "node:fs";
import postcss from "postcss";
import prefixer from "postcss-prefix-selector";

const SCOPE = ".eg-shop";
const FILES = ["bootstrap.min.css", "bootstrap-icons.css", "owl.carousel.min.css", "owl.theme.default.min.css", "all.min.css", "style.css", "responsive.css"];

const plugin = prefixer({
  prefix: SCOPE,
  transform(prefix, selector, prefixed) {
    const s = selector.trim();
    if (s === "html" || s === "body" || s === ":root" || s === "html body") return prefix;
    if (/^(html|body)[\s>.:[#]/.test(s)) return prefix + s.replace(/^(html|body)/, "");
    if (/^:root[\s>.:[#]/.test(s)) return prefix + s.replace(/^:root/, "");
    return prefixed;
  },
});

const rewrite = {
  postcssPlugin: "shop-rewrite",
  // Once, not Declaration: a Declaration visitor runs again on every change.
  Once(root) {
    root.walkDecls((decl) => {
      if (/url\(/.test(decl.value)) {
        decl.value = decl.value
          .replace(/url\((['"]?)(?:\.\.\/|\.\/)?(?:webfonts|fonts)\//g, "url($1/shop/webfonts/")
          .replace(/url\((['"]?)\.\.\/image\//g, "url($1/shop/images/")
          .replace(/url\((['"]?)\.\.\/icon\//g, "url($1/shop/images/icon/")
          .replace(/url\((['"])\1\)/g, "none") // the legacy preloader's empty url('')
          .replace(/url\((['"]?)owl\.video\.play\.png/g, "url($1/shop/images/owl.video.play.png");
      }
      // Only woff2 / woff are shipped (public/shop/webfonts/).
      if (decl.prop === "src" && decl.parent?.type === "atrule" && decl.parent.name === "font-face") {
        const kept = decl.value
          .split(/,(?![^(]*\))/)
          .map((part) => part.trim())
          .filter((part) => /\.woff2?(?:[?#"')]|$)/.test(part));
        if (kept.length > 0) decl.value = kept.join(", ");
        else decl.remove(); // the IE9 `src:url(x.eot)` line
      }
      if (decl.prop === "font-family") {
        decl.value = decl.value
          .replace(/['"]?Roboto['"]?/, "var(--font-roboto), 'Roboto'")
          .replace(/['"]?Merienda['"]?/, "var(--font-merienda), 'Merienda'");
      }
    });
  },
};

let out = `/* GENERATED by scripts/scope-shop-css.mjs from design/webapp-css/. Do not edit by hand.
   Every selector is scoped under ${SCOPE} so the admin and seller panels are not affected. */\n`;
for (const file of FILES) {
  const css = readFileSync(`design/webapp-css/${file}`, "utf8");
  const result = await postcss([rewrite, plugin]).process(css, { from: undefined });
  const cleaned = result.css;
  out += `\n/* ===== ${file} ===== */\n${cleaned}\n`;
}
writeFileSync("src/styles/shop.css", out);
console.log(`src/styles/shop.css: ${(out.length / 1024).toFixed(0)} KB`);
